"""Write modalities/spine_mri/models/disc-grader.md from the trained grader's grader.json and SCORECARD.md, so
every number in the card comes from those files and none is typed by hand.
Usage: python model_card.py [--version 1]"""
import argparse
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.dirname(HERE))))  # the repository root
from core import paths  # noqa: E402
MODELS = paths.MODELS


def score_rows(split):
    card = open(os.path.join(HERE, "SCORECARD.md"), encoding="utf-8").read()
    out = []
    for m in re.finditer(rf"^\| {split} \| (\w+) \| (\w+) \| grader \| (tss|spider_masks) \| (\d+) \| (\d+) \| (\S+) \| (\S+) \| (\S+) \| \d+ \|$",
                         card, re.M):
        out.append(m.groups())
    return out


def table(rows):
    if not rows:
        return ["Not yet run."]
    L = ["| item | metric | localisation | discs | patients | value | 95% CI |", "|---|---|---|---|---|---|---|"]
    for item, metric, loc, nd, npt, v, lo, hi in rows:
        L.append(f"| {item} | {metric} | {loc} | {nd} | {npt} | {v} | {lo} to {hi} |")
    return L


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--version", type=int, default=1)
    a = ap.parse_args()
    d = os.path.join(MODELS, f"disc-grader-v{a.version}")
    meta = json.load(open(os.path.join(d, "grader.json")))
    final = os.path.join(paths.WORK, "eval", "final_eval.json")
    ship = json.load(open(final)).get("ship", {}).get("grader") if os.path.exists(final) else None
    L = [f"# Model card: rAidiology disc grader v{a.version}", "",
         "Generated by `modalities/spine_mri/eval/model_card.py` from the model's `grader.json` and `modalities/spine_mri/eval/SCORECARD.md`.", "",
         "**TSS weights: permission pending.** The grader's crops are centred with TotalSpineSeg's disc labels, whose "
         "released weights NeuroPoly has not yet cleared for commercial use. Nothing that depends on them goes into a "
         "paid product until they do (`LICENSING.md`).", "",
         "## What it does", "",
         "Grades one lumbar disc (T12-L1 to L5-S1) from a sagittal MRI: Pfirrmann grade 1-5 and the probability of "
         "herniation, narrowing, bulging, spondylolisthesis, upper and lower endplate change and any Modic change. "
         "It is a research tool for a second look, not a diagnosis, and not a medical device.", "",
         "## Data and licences", "",
         "- Trained on SPIDER (Zenodo 10159290, CC BY 4.0) development patients only "
         f"({meta['n_patients']} patients, {meta['n_discs']} discs located by TotalSpineSeg); the 44 held-out test "
         "patients were never used for training, calibration or any choice.",
         "- The truth is one musculoskeletal radiologist's grading of a Dutch back-pain cohort.",
         "- Trained from scratch: no pretrained backbone (ImageNet terms are non-commercial).",
         f"- Disc localisation: {meta['localisation']}.", "",
         "## Inputs and model", "",
         f"- Inputs: {meta['inputs']}; T1 missing -> zero channel plus a flag; each series scaled by its 1st/99th percentiles.",
         "- Network: four convolutional stages, an ordinal head (four cumulative logits) for Pfirrmann and one sigmoid "
         "logit per binary item. Pfirrmann = 1 + the number of cumulative probabilities above 0.5.",
         f"- Training settings: `{json.dumps(meta['cfg'])}`.",
         "- Five fold models (5-fold cross-validation by patient); the shipped model averages their logits.", "",
         "## Calibration", "",
         "Temperatures are fitted on nested out-of-fold ensembles (each outer fold predicted by an average of four inner "
         "models), so a stated probability means about that rate for the averaged model. Expected calibration error, "
         "cross-fitted (each fold calibrated on the other four), single fold models vs nested ensembles:", "",
         "| output | single models | nested ensembles |", "|---|---|---|"]
    s, n = meta["calibration"]["single"]["ece_cross_fitted"], meta["calibration"]["nested"]["ece_cross_fitted"]
    for k in s:
        L.append(f"| {k} | {s[k]:.3f} | {n[k]:.3f} |")
    L += ["", "Thresholds for the yes/no flags (Youden's J on the nested-ensemble development predictions): "
          + ", ".join(f"{k} {v:.3f}" for k, v in meta["thresholds"].items()) + ".", "",
          "## Metrics", "",
          "Development, each fold model on its own held-out fold (95% CI, 2,000 patient bootstrap resamples):", ""]
    L += table(score_rows("dev"))
    L += ["", "Held-out test, the shipped five-model ensemble, scored once in the final evaluation:", ""]
    L += table(score_rows("test"))
    if ship:
        L += ["", f"Ship rule (Pfirrmann kappa minus the reference baseline's, paired by patient): difference "
              f"{ship['difference']}, 95% CI {ship['ci_low']} to {ship['ci_high']}: "
              + ("**ships**." if ship["ships"] else "**does not ship**.")]
    L += ["", "## Files", "", f"Weights in `Models/disc-grader-v{a.version}/` (outside the repository), trained {meta['trained']}:", ""]
    for f, h in meta["weights"].items():
        L.append(f"- `{f}` SHA-256 `{h}`")
    L += ["", "## Limits", "",
          "- Lumbar only; cervical levels keep rAidiology's reading and measurements.",
          "- Scores on SPIDER are optimistic for localisation: TotalSpineSeg was trained on SPIDER's images.",
          "- One radiologist's grades on one country's back-pain patients; other readers and populations differ.", ""]
    os.makedirs(os.path.join(HERE, "..", "models"), exist_ok=True)
    out = os.path.join(HERE, "..", "models", "disc-grader.md")
    open(out, "w", encoding="utf-8").write("\n".join(L))
    print("wrote", os.path.normpath(out))


if __name__ == "__main__":
    main()
