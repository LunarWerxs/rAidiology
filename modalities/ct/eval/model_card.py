"""Write the CT segmenter's model card from the files the work itself produced.

Nothing in the card is typed by hand. The settings and the learning curves come from the model's
`meta.json`, the counts from `split.json`, every score from the tab-separated cells the scorer wrote
(the same cells the independent recomputation checked), the ship decision from the final
evaluation's own record, and the ceiling and timings from the run ledger. A number that is not in
one of those files is not in the card; where a file does not exist yet the card says so instead of
leaving a gap that reads as a result.

    python modalities/ct/eval/model_card.py [--version 1]
"""
import argparse
import json
import os
import sys

import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.dirname(HERE))))
import datasets  # noqa: E402
import score  # noqa: E402  arkitect-allow: test-floor-loosened - a sibling module after the sys.path lines, as datasets is
from core import ledger, paths  # noqa: E402

OUT = os.path.join(paths.WORK, "eval", "ct")
CARD = os.path.join(os.path.dirname(HERE), "models", "segmenter.md")
METHOD = "segmenter"


def curve_dice(point):
    """A learning-curve point's Dice. Version 1's meta.json, a shipped file, wrote it as `dice_3mm`
    (every look on the 3 mm grid); from version 2 a look is taken at its phase's own grid and
    written as `dice`, with the grid in `mm`."""
    return point["dice"] if "dice" in point else point["dice_3mm"]


def cells(path):
    out = {}
    if not os.path.exists(path):
        return out
    with open(path, encoding="utf-8") as f:
        for line in f:
            p = line.rstrip("\n").split("\t")
            if len(p) == 6:
                out[tuple(p[:3])] = tuple(float(v) for v in p[3:])
    return out


def last(kind, name):
    """The newest ledger run of that kind and name that finished, or None."""
    runs = [r for r in ledger.records(kind) if r.get("name") == name and r.get("ok", 1)]
    return runs[-1] if runs else None


def number(run, key):
    return run["numbers"][key]["value"] if run and key in run.get("numbers", {}) else None


def with_interval(c, key, signed=False):
    if key not in c:
        return "not scored"
    v, lo, hi = c[key]
    return ("%+.4f (%+.4f to %+.4f)" if signed else "%.4f (%.4f to %.4f)") % (v, lo, hi)


def strata_table(c, reference):
    rows = ["| scans in | segmenter | %s | difference (95%% CI) | invents a structure |" % reference,
            "|---|---:|---:|---:|---:|"]
    seen = []
    for stratum, method, metric in c:
        if stratum not in seen:
            seen.append(stratum)
    for s in seen:
        rows.append("| %s | %s | %s | %s | %s |" % (
            s, with_interval(c, (s, METHOD, "headline_dice")),
            "%.4f" % c[(s, reference, "headline_dice")][0] if (s, reference, "headline_dice") in c else "not scored",
            with_interval(c, (s, METHOD, "headline_dice_minus_reference"), signed=True),
            with_interval(c, (s, METHOD, "invention_rate"))))
    return rows


def build(version):
    import segmenter  # noqa: PLC0415  for the model folder; imports torch

    meta = json.load(open(os.path.join(segmenter.model_dir(version), "meta.json"), encoding="utf-8"))
    split = json.load(open(os.path.join(HERE, "split.json"), encoding="utf-8"))
    state_file = os.path.join(OUT, "final_eval.json")
    state = json.load(open(state_file, encoding="utf-8")) if os.path.exists(state_file) else {}
    dev = cells(os.path.join(OUT, "scorecard_dev.tsv"))
    test = cells(os.path.join(OUT, "scorecard_test.tsv")) if state.get("finished") else {}
    reference = state.get("reference", "the reference")
    cfg = meta["cfg"]
    ceiling = number(last("measurement", "ct ceiling of the 3 mm grid"), "mean_dice")
    overlap = number(last("measurement", "ct ceiling of the 3 mm grid"), "overlap_share")
    reading = number(last("segmenter", "predict test v%d" % version), "seconds_per_scan")

    L = ["# Model card: rAidiology CT segmenter v%d" % version, "",
         "Generated by `modalities/ct/eval/model_card.py` from the model's `meta.json`, "
         "`modalities/ct/eval/split.json`, the scorer's cells and the run ledger. No number in it was "
         "typed by hand.", "",
         "**Not a medical device.** It labels anatomy for a picture and for measurements; it is not a "
         "diagnosis and it does not look for disease (`LICENSING.md`).", "",
         "## What it answers", "",
         "One question, fixed before any model was trained: **where is each organ and bone in this "
         "scan?** One label per voxel over the %d structures the TotalSegmentator dataset marks. It "
         "does not say whether any of them is healthy." % len(meta["structures"]), "",
         "## What it was trained on", "",
         "- %s" % meta["dataset"],
         "- %d development scans in %d folds; %d held-out test scans, the dataset authors' own test "
         "split, never used for training or for any choice."
         % (len(split["dev_folds"]), split["folds"], len(split["test"])),
         "- **Trained from scratch, with no pretrained weights of any kind.** No ImageNet, no model "
         "zoo: every weight was learned from those CC BY 4.0 scans, so the model carries no "
         "'permission pending' and the attribution above is what the licence asks for.",
         "- %s" % split["unit_note"], "",
         "## Model", "",
         "- A 3D U-Net, widths %s, two 3 x 3 x 3 convolutions a stage, normalised per scan."
         % " - ".join(str(w) for w in cfg["widths"]),
         "- It reads the scan at %.0f mm (each 2 x 2 x 2 block of the 1.5 mm scan averaged) in cubes "
         "of %d voxels, and its probabilities are interpolated back to 1.5 mm before a label is "
         "chosen. Every score below is taken at 1.5 mm, against the expert masks as published."
         % (meta["spacing_mm"], cfg["patch"]),
         "- %d fold models; each development score comes from the model that never saw that scan, "
         "and the test split is read by all of them, their probabilities averaged." % len(meta["folds"]),
         "- A fixed schedule a fold (%s): nothing was stopped early or chosen by looking at held-out "
         "scans." % ", then ".join("%d steps at %g mm" % (ph["steps"], ph["mm"])
                                   for ph in segmenter.phases_of(cfg)),
         "- Training settings: `%s`." % json.dumps(cfg, sort_keys=True),
         "- Trained %s with torch %s." % (meta["trained"], meta["torch"]), "",
         "| fold | trained on | held out | minutes | mean Dice on %d held-out scans, by step, on the coarse grid |"
         % cfg["curve_scans"],
         "|---:|---:|---:|---:|---|"]
    for f in meta["folds"]:
        L.append("| %d | %d | %d | %.0f | %s |" % (
            f["fold"], f["train_scans"], f["held_scans"], f["seconds"] / 60.0,
            ", ".join("%d: %.3f" % (p["step"], curve_dice(p)) if curve_dice(p) == curve_dice(p)
                      else "%d: not taken" % p["step"] for p in f["curve"])))
    L += ["", "The last column is the learning curve, a quick look on the coarse grid drawn while "
          "training. It is not a score and nothing was chosen by it. The early points are low on "
          "purpose: they are taken at 3 mm while the network is still in its 6 mm phase. A point "
          "marked not taken ran out of room under the memory ceiling; the fold itself was unaffected.", ""]

    L += ["## Held-out test", ""]
    if test:
        r = state["ship_result"]
        L += ["Opened once, on %s. Reference: **%s**, the strongest baseline on development, fixed "
              "before the test was opened." % (state["test_opened"], reference), "",
              "**Segmenter minus %s: %+.4f (95%% CI %+.4f to %+.4f) on %d scans. %s**"
              % (reference, r["difference"], r["ci_low"], r["ci_high"], state["test_scans"],
                 "It ships." if r["ships"] else "It does not ship."), ""]
        L += strata_table(test, reference) + [""]
    else:
        L += ["Not opened yet. `final_eval.py` opens it once, and this section is written from what "
              "it records.", ""]

    L += ["## Development, out of fold", ""]
    if (("all", METHOD, "headline_dice") in dev) and state.get("reference"):
        L += strata_table(dev, reference) + [""]
    else:
        L += ["Not scored yet.", ""]

    L += ["## What to hold against it", "",
          "- **The scan is the unit, not the patient.** The dataset publishes no patient identifier, "
          "so every interval above treats two scans of one person as independent.",
          "- **One dataset.** Most of its scans come from one institute and one manufacturer; the "
          "strata above are the only evidence about anything else, and they are small.",
          "- **Measured at 1.5 mm only.** A scan at another spacing is resampled, and that path has "
          "no scorecard behind it; the reading says so when it happens.",
          "- **It invents structures.** The last column above is how often it outlines a structure "
          "the scan does not contain. Dice never sees that, which is why it has its own column."]
    if ceiling is not None:
        L.append("- **The working grid has a ceiling.** Labels at 3 mm, reproduced perfectly, would "
                 "score %.4f mean Dice at 1.5 mm. The model interpolates probabilities, so it is not "
                 "strictly bound by that figure, but thin structures pay for the coarse grid." % ceiling)
    if overlap is not None:
        L.append("- **A perfect answer scores under 1.** The expert masks overlap in %.2f%% of marked "
                 "voxels, and this model gives one label per voxel." % (100 * overlap))
    L += ["- **Per structure, not just on average.** `eval/SCORECARD.md` lists all %d structures; "
          "the weakest are the ones to distrust in a picture." % len(meta["structures"]), "",
          "## Running it", "",
          "    python modalities/ct/eval/segmenter.py scan <ct.nii.gz> --out labels.nii.gz", "",
          "Weights: `Models/ct-segmenter-v%d/` beside the repository (%d files, checksums in "
          "`meta.json`)." % (version, len(meta["folds"]))]
    if reading is not None:
        L.append("A test scan took %.1f s on the graphics card it was trained on, all fold models "
                 "included. Its cost on a processor has not been measured." % reading)
    L += ["", "---", "", "Not a medical device. These are measurements on a public research dataset, "
          "not a claim about anybody's scan."]
    return "\n".join(L) + "\n"


def facts(version):
    """What a reading of one scan quotes about the model (mcp/server.py's read_ct): the held-out test
    as final_eval.py recorded it, and each structure's own Dice on the test scans that contain it, so
    an outline is given with how far that kind of outline can be trusted. Taken from the scorer's
    cells and its rows, never typed; None until the test has been opened."""
    state_file = os.path.join(OUT, "final_eval.json")
    state = json.load(open(state_file, encoding="utf-8")) if os.path.exists(state_file) else {}
    if not state.get("finished") or state.get("version") != version:
        return None
    test = cells(os.path.join(OUT, "scorecard_test.tsv"))
    rows = pd.read_csv(os.path.join(OUT, "pred_%s_test.csv" % METHOD), dtype={"scan": str})
    scans = sorted(rows["scan"].unique())
    per = score.per_method(rows, scans, score.Draws(scans, 0, datasets.SEED))["per_structure"]
    r = state["ship_result"]
    return {"version": version, "made_by": "modalities/ct/eval/model_card.py",
            "test_scans": state["test_scans"], "test_opened": state["test_opened"],
            "mean_dice": list(test[("all", METHOD, "headline_dice")]),
            "invention_rate": list(test[("all", METHOD, "invention_rate")]),
            "reference": state["reference"],
            "minus_reference": [r["difference"], r["ci_low"], r["ci_high"]],
            "per_structure_test_dice": {n: [round(d, 4), k] for n, (d, k) in sorted(per.items())}}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--version", type=int, default=1)
    a = ap.parse_args()
    text = build(a.version)
    os.makedirs(os.path.dirname(CARD), exist_ok=True)
    with open(CARD, "w", encoding="utf-8") as f:
        f.write(text)
    print("%s (%d lines)" % (CARD, text.count("\n")))
    known = facts(a.version)
    if known:
        out = os.path.join(os.path.dirname(CARD), "segmenter-v%d.json" % a.version)
        with open(out, "w", encoding="utf-8") as f:
            json.dump(known, f, indent=1)
        print("%s (%d structures)" % (out, len(known["per_structure_test_dice"])))


if __name__ == "__main__":
    main()
